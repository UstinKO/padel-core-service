package com.padle.core.padelcoreservice.model.enums;

/**
 * Тип формата Americano-турнира.
 *
 * FULL  — каждая уникальная пара игроков сыграла в одной команде ровно 1 раз,
 *         повторов нет, все пары покрыты. Присваивается только после пост-проверки.
 * FLEX  — гибкий формат: допускаются повторы партнёров / соперников, bye,
 *         неполное покрытие пар. Используется когда Full математически невозможен
 *         или пост-проверка не прошла.
 * AUTO  — режим генерации: система сама выбирает Full или Flex.
 *         После генерации заменяется на FULL или FLEX.
 */
public enum AmericanoFormatType {
    FULL,
    FLEX,
    AUTO
}